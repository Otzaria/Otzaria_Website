// זמן-התפיסה בלי שבת וחג (lease.js): החלונות בשעון ירושלים, ימי-החג מהלוח העברי של Intl,
// חג סמוך לשבת, מעבר-שעון, ותפיסה שמתחילה בתוך חלון. הבדיקות אינן תלויות באזור-הזמן של
// המחשב שמריץ אותן — כל רגע נבנה ב-jerusalemTime.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { leaseEnd, restWindows, isRestTime, isYomTov, restOverlap, jerusalemTime, REST_NOTE, checkCalendar, CALENDAR_CHECK } from './lease.js';
import { CLAIM_HOURS } from './gridState.js';

const HOUR = 3600 * 1000;
const J = jerusalemTime;
const ms = (d) => (d instanceof Date ? d.getTime() : d);
// התפיסה נגמרת ב-`end` (רגע בשעון ירושלים)
const ends = (start, end, hours = CLAIM_HOURS) => assert.equal(ms(leaseEnd(start, hours)), end);

test('יום חול: בדיוק 48 שעות', () => {
  assert.equal(CLAIM_HOURS, 48);
  // שני 5.10.2026 10:00 ← רביעי 10:00
  ends(J(2026, 10, 5, 10), J(2026, 10, 7, 10));
  assert.equal(ms(leaseEnd(J(2026, 10, 5, 10))) - J(2026, 10, 5, 10), 48 * HOUR);
  // Date, מספר ומחרוזת — אותו דבר
  const s = J(2026, 10, 5, 10);
  assert.equal(ms(leaseEnd(new Date(s))), ms(leaseEnd(s)));
  assert.equal(ms(leaseEnd(new Date(s).toISOString())), ms(leaseEnd(s)));
  assert.ok(leaseEnd(s) instanceof Date);
});

test('על פני שבת: שישי 12:00 עד מוצ"ש 22:00 אינם נספרים', () => {
  // חמישי 8.10.2026 10:00: עד שישי 12:00 — 26 שעות; אחרי מוצ"ש 22:00 עוד 22 ← ראשון 20:00
  ends(J(2026, 10, 8, 10), J(2026, 10, 11, 20));
  // שישי 11:00: שעה אחת לפני השבת, ו-47 אחריה ← שני 21:00
  ends(J(2026, 10, 9, 11), J(2026, 10, 12, 21));
  // בדיוק בכניסת החלון (שישי 12:00) — הספירה מתחילה במוצ"ש 22:00
  ends(J(2026, 10, 9, 12), J(2026, 10, 12, 22));
  // בתוך השבת — כנ"ל
  ends(J(2026, 10, 10, 15), J(2026, 10, 12, 22));
  // בדיוק ביציאה (מוצ"ש 22:00) — 48 שעות רגילות
  ends(J(2026, 10, 10, 22), J(2026, 10, 12, 22));
  // תפיסה שמסתיימת בדיוק בכניסת השבת — לא מתארכת (48 שעות מלאות כבר ניתנו)
  ends(J(2026, 10, 7, 12), J(2026, 10, 9, 12));
});

test('isRestTime: גבולות החלון — תחילתו בפנים, סופו בחוץ; ימי חול', () => {
  assert.equal(isRestTime(J(2026, 10, 9, 11, 59)), false);
  assert.equal(isRestTime(J(2026, 10, 9, 12)), true);
  assert.equal(isRestTime(J(2026, 10, 10, 21, 59)), true);
  assert.equal(isRestTime(J(2026, 10, 10, 22)), false);
  assert.equal(isRestTime(J(2026, 10, 7, 12)), false); // רביעי רגיל
  // חול-המועד סוכות (י"ח בתשרי תשפ"ז, רביעי 30.9.2026) — יום חול
  assert.equal(isRestTime(J(2026, 9, 30, 15)), false);
  assert.equal(isYomTov(2026, 9, 30), false);
});

test('ימי-החג בארץ-ישראל לפי הלוח העברי (Intl), ורק הם', () => {
  // תשפ"ז: ר"ה שבת-ראשון 12–13.9.2026, יוה"כ שני 21.9, סוכות שבת 26.9, שמיני עצרת שבת 3.10
  for (const [m, d] of [[9, 12], [9, 13], [9, 21], [9, 26], [10, 3]]) assert.equal(isYomTov(2026, m, d), true, `2026-${m}-${d}`);
  // פסח תשפ"ז: חמישי 22.4.2027 ורביעי 28.4.2027; שבועות: שישי 11.6.2027
  for (const [m, d] of [[4, 22], [4, 28], [6, 11]]) assert.equal(isYomTov(2027, m, d), true, `2027-${m}-${d}`);
  // לא חג: ערב ר"ה, יום-טוב שני של גלויות (כ"ג בתשרי), חול-המועד פסח, פורים, ט' באב
  for (const [y, m, d] of [[2026, 9, 11], [2026, 10, 4], [2027, 4, 25], [2027, 3, 23], [2027, 8, 12]]) {
    assert.equal(isYomTov(y, m, d), false, `${y}-${m}-${d}`);
  }
});

test('חג סמוך לשבת — חלון אחד רצוף', () => {
  // ר"ה תשפ"ז בשבת וביום ראשון: שישי 11.9 12:00 עד ראשון 13.9 22:00
  const rh = restWindows(J(2026, 9, 10, 0), J(2026, 9, 15, 0));
  assert.deepEqual(rh, [[J(2026, 9, 11, 12), J(2026, 9, 13, 22)]]);
  // חמישי 10.9 12:00: 24 שעות עד שישי 12:00, ו-24 אחרי ראשון 22:00 ← שני 14.9 22:00
  ends(J(2026, 9, 10, 12), J(2026, 9, 14, 22));
  // שבועות תשפ"ז ביום שישי: חמישי 10.6 12:00 עד מוצ"ש 12.6 22:00
  const sh = restWindows(J(2027, 6, 9, 0), J(2027, 6, 14, 0));
  assert.deepEqual(sh, [[J(2027, 6, 10, 12), J(2027, 6, 12, 22)]]);
  // רביעי 9.6 12:00: 24 עד חמישי 12:00, ועוד 24 ← ראשון 13.6 22:00
  ends(J(2027, 6, 9, 12), J(2027, 6, 13, 22));
});

test('יום הכיפורים אחרי שבת: שני חלונות, והפער ביניהם נספר', () => {
  // שבת 19.9.2026, ויוה"כ ביום שני 21.9 (ערב: ראשון 12:00)
  const w = restWindows(J(2026, 9, 18, 0), J(2026, 9, 23, 0));
  assert.deepEqual(w, [
    [J(2026, 9, 18, 12), J(2026, 9, 19, 22)],
    [J(2026, 9, 20, 12), J(2026, 9, 21, 22)],
  ]);
  // שישי 10:00: 2 שעות, ואז מוצ"ש 22:00 עד ראשון 12:00 — 14 (סה"כ 16), ואז 32 אחרי שני 22:00 ← רביעי 06:00
  ends(J(2026, 9, 18, 10), J(2026, 9, 23, 6));
});

test('פסח: ערב-החג באמצע השבוע, ושביעי של פסח', () => {
  // ט"ו בניסן תשפ"ז — חמישי 22.4.2027; שביעי של פסח — רביעי 28.4.2027
  const w = restWindows(J(2027, 4, 20, 0), J(2027, 4, 29, 0));
  assert.deepEqual(w, [
    [J(2027, 4, 21, 12), J(2027, 4, 22, 22)],
    [J(2027, 4, 23, 12), J(2027, 4, 24, 22)],
    [J(2027, 4, 27, 12), J(2027, 4, 28, 22)],
  ]);
  // שלישי 20.4 12:00: 24 עד רביעי 12:00; חמישי 22:00 עד שישי 12:00 — 14 (38); עוד 10 אחרי מוצ"ש ← ראשון 08:00
  ends(J(2027, 4, 20, 12), J(2027, 4, 25, 8));
});

test('מעבר שעון: הספירה בשעות אמיתיות, והחלון לפי שעון-הקיר', () => {
  // סוף שעון-הקיץ 2026: ראשון 25.10 02:00. חמישי 22.10 18:00 (UTC+3): 18 שעות עד שישי 12:00,
  // ועוד 30 אחרי מוצ"ש 22:00 (UTC+3) ← שני 26.10 03:00 (UTC+2) — שעון-הקיר זז שעה אחורה בדרך
  const s1 = J(2026, 10, 22, 18);
  ends(s1, J(2026, 10, 26, 3));
  assert.equal(ms(leaseEnd(s1)) - s1, 82 * HOUR);
  assert.equal(J(2026, 10, 26, 3), Date.UTC(2026, 9, 26, 1));
  // תחילת שעון-הקיץ 2026: שישי 27.3 02:00. חמישי 26.3 12:00 (UTC+2) ← שישי 12:00 (UTC+3) = 23 שעות אמיתיות;
  // ועוד 25 אחרי מוצ"ש 22:00 ← ראשון 29.3 23:00
  const s2 = J(2026, 3, 26, 12);
  ends(s2, J(2026, 3, 29, 23));
  assert.equal(ms(leaseEnd(s2)) - s2, 82 * HOUR);
  // החלון עצמו בשבוע של המעבר — 12:00 ו-22:00 בשעון-הקיר
  assert.deepEqual(restWindows(J(2026, 3, 26, 0), J(2026, 3, 29, 0)), [[J(2026, 3, 27, 12), J(2026, 3, 28, 22)]]);
  assert.equal(J(2026, 3, 27, 12), Date.UTC(2026, 2, 27, 9));
});

test('בכל תפיסה: בדיוק 48 שעות מחוץ לחלונות — סריקה של שנה שלמה', () => {
  // כל 7 שעות במשך שנה (כ-1,250 נקודות-התחלה, כולל כל החגים ושני מעברי-השעון)
  const t0 = J(2026, 9, 1, 0);
  for (let t = t0; t < t0 + 365 * 24 * HOUR; t += 7 * HOUR) {
    const e = ms(leaseEnd(t));
    assert.equal(e - t - restOverlap(t, e), 48 * HOUR, new Date(t).toISOString());
    assert.equal(isRestTime(e - 1), false, `השעה האחרונה נספרה: ${new Date(t).toISOString()}`);
  }
});

test('משכים אחרים, וקלט לא תקין', () => {
  ends(J(2026, 10, 8, 10), J(2026, 10, 8, 11), 1);
  ends(J(2026, 10, 9, 13), J(2026, 10, 10, 22), 0); // 0 שעות בתוך שבת — היציאה ממנה
  assert.throws(() => leaseEnd('לא תאריך'), TypeError);
  assert.match(REST_NOTE, /שבת וחג/);
  assert.deepEqual(restWindows(J(2026, 10, 12, 0), J(2026, 10, 11, 0)), []);
});

test('בדיקה-עצמית של הלוח: תאריכים ידועים — יום-טוב (גם בשנה מעוברת), וחול — לא', () => {
  assert.equal(checkCalendar(), true);
  for (const [y, m, d, want] of CALENDAR_CHECK) assert.equal(isYomTov(y, m, d), want, `${y}-${m}-${d}`);
});
