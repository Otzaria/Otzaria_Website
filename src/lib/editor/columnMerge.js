// איחוד שני טורים לטור אחד (העורך: "איחוד טורים"). הטור הימני ואחריו השמאלי, בשורה נפרדת —
// בלי '\n' ביניהם השורה האחרונה של הימני והראשונה של השמאלי היו נדבקות לשורה אחת.
// טור ריק לא מוסיף שורה ריקה (פיצול שהשאיר את השמאלי ריק מתאחד בחזרה לטקסט המקורי בדיוק),
// וכשהימני כבר מסתיים ב-'\n' לא מוסיפים עוד אחד.
export function mergeColumns(right = '', left = '') {
  const r = right ?? ''
  const l = left ?? ''
  if (!l) return r
  if (!r) return l
  return r.endsWith('\n') ? r + l : `${r}\n${l}`
}
