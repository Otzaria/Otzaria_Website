// הטקסטים של אישור עמודים בסקירת גלאי-האזורים — יחיד ורבים ("אשר את העמוד", לא "אשר את 1 העמודים")
import { fmt } from '../api'

/** כפתור "אשר" בכרטיס ספר */
export const approveBookLabel = (n) => (n === 1 ? 'אשר את העמוד' : `אשר את ${fmt(n)} העמודים`)

/** כפתור "אשר את כל מה שסומן" בתוך ספר */
export const approveMarkedLabel = (n) => (n === 1 ? 'אשר את העמוד שסומן' : `אשר את כל העמודים שסומנו (${fmt(n)})`)

/** חלון האישור: כותרת והסבר */
export const approveConfirm = (n, alias) => ({
  title: n === 1 ? `לאשר עמוד אחד ב${alias}?` : `לאשר ${fmt(n)} עמודים ב${alias}?`,
  message: n === 1 ? 'העמוד ייכנס לקובץ הבא שתורידו לתחנה, כמסגרות מאושרות.' : 'העמודים ייכנסו לקובץ הבא שתורידו לתחנה, כמסגרות מאושרות.',
})
