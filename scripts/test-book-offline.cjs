const path = require('node:path');
const fs = require('node:fs');
const { spawn } = require('node:child_process');
const root = process.cwd();
const req = require('node:module').createRequire(path.join(root, 'package.json'));
const { MongoMemoryServer } = req('mongodb-memory-server-core');
const mongoose = req('mongoose');
const { encode } = req('next-auth/jwt');
const { chromium } = require(process.env.OTZARIA_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const artifacts = process.env.OTZARIA_BOOK_OFFLINE_ARTIFACTS || fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'otzaria-book-offline-'));
fs.mkdirSync(artifacts, {recursive:true});
const log = fs.openSync(path.join(artifacts, 'build.log'), 'w');
const imageDirectory = 'public/uploads/offline-book-qa-' + process.pid;
const imagePath = '/uploads/offline-book-qa-' + process.pid + '/scan.png';
let mongod, app, browser;
(async () => {
  mongod = await MongoMemoryServer.create();
  const uri = mongod.getUri('offline_smoke');
  await mongoose.connect(uri);
  const { default: Book } = await import(path.join(root, 'src/models/Book.js'));
  const { default: Page } = await import(path.join(root, 'src/models/Page.js'));
  const { default: User } = await import(path.join(root, 'src/models/User.js'));
  const user = await User.create({ name: 'בדיקת אופליין', email: 'offline@example.invalid', isVerified: true, acceptReminders: true, hiddenInstructionsBooks: ['offline-smoke'] });
  const book = await Book.create({ name: 'ספר לבדיקת אופליין', slug: 'offline-smoke', totalPages: 2 });
  fs.mkdirSync(imageDirectory, {recursive:true});
  const sharp = req('sharp');
  await sharp({create:{width:600,height:900,channels:3,background:'#fff'}}).png().toFile(path.join(imageDirectory, 'scan.png'));
  for (const n of [1,2]) await Page.create({ book:book._id,pageNumber:n,content:`טקסט התחלתי ${n}`,imagePath,status:'in-progress',claimedBy:user._id });
  const secret = 'offline-local-fixture-secret-only';
  const portServer = require('node:net').createServer();
  await new Promise(resolve => portServer.listen(0, '127.0.0.1', resolve));
  const port = portServer.address().port;
  await new Promise(resolve => portServer.close(resolve));
  const baseUrl = 'http://localhost:' + port;
  const env = {...process.env,MONGODB_URI:uri,NEXTAUTH_SECRET:secret,NEXTAUTH_URL:baseUrl,MONGODB_SERVER_SELECTION_TIMEOUT_MS:'2000'};
  console.log('Building a production app against an isolated temporary database; artifacts: ' + artifacts);
  const build = spawn('npm',['run','build'],{env,stdio:['ignore',log,log]});
  await new Promise((resolve,reject)=>build.once('exit',code=>code===0?resolve():reject(new Error('Build failed: '+code))));
  console.log('Production build passed. Starting browser checks.');
  app=spawn(process.execPath,[req.resolve('next/dist/bin/next'),'start','-p',String(port)],{env,stdio:['ignore',log,log]});
  await new Promise((resolve,reject)=>{const end=Date.now()+20000;const check=()=>fetch(baseUrl + '/version.json').then(()=>resolve()).catch(()=>Date.now()<end?setTimeout(check,300):reject(new Error('start timed out')));check()});
  browser=await chromium.launch({headless:true,...(process.env.OTZARIA_CHROME_EXECUTABLE ? {executablePath:process.env.OTZARIA_CHROME_EXECUTABLE} : {})});
  const context=await browser.newContext({userAgent:'Mozilla/5.0 offline QA Googlebot',viewport:{width:1365,height:900}});
  const token=await encode({secret,token:{id:String(user._id),role:'user',name:user.name,email:user.email,isVerified:true,acceptReminders:true}});
  await context.addCookies([{name:'next-auth.session-token',value:token,domain:'localhost',path:'/'}]);
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('hide_instructions_offline-smoke','true'));
  await page.goto(baseUrl + '/library/books/offline-smoke/1');
  await page.getByRole('button',{name:'הכנת העמוד לאופליין'}).waitFor();
  await page.getByRole('button',{name:'הכנת העמוד לאופליין'}).click();
  await page.getByRole('button',{name:'אפשר עריכה אופליין לעמוד זה',exact:true}).click();
  await page.getByRole('button',{name:'ניהול עמודים אופליין'}).waitFor({timeout:60000});
  // Enabling briefly remounts the editor while acquiring its cross-tab lock.
  await page.locator('[data-editor-shell]').waitFor();
  await page.screenshot({path:path.join(artifacts,'online.png'),fullPage:true});
  console.log('Prepared the real editor and scan.');
  const recordKey=await page.evaluate(()=>Object.keys(localStorage).find(k=>k.startsWith('otzaria:offline-book:v1:')));
  assert(recordKey);
  const other=await context.newPage();
  const blockedReads=[];
  other.on('request', request=>{if(request.url().includes('/api/page-content?'))blockedReads.push(request.url())});
  await other.goto(page.url());
  await other.getByText('עמוד זה פתוח לעריכה בלשונית אחרת.',{exact:false}).waitFor();
  assert.deepEqual(blockedReads,[],'A blocked tab must not refresh another editor’s journal');
  await other.close();

  // A new edit after a clean mount must recover without a focus or online event.
  let failedSaves=0;
  let resolveFailure;
  const firstFailure=new Promise(resolve=>{resolveFailure=resolve});
  await page.route('**/api/page-content',async route=>{
    if(route.request().method()==='POST' && failedSaves===0){
      failedSaves++;
      await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'temporary QA failure'})});
      resolveFailure();
    } else await route.continue();
  });
  await page.locator('textarea[data-column="content"], [data-rich-textarea][contenteditable="true"]').first().fill('עריכה שהתאוששה מכשל זמני');
  await Promise.race([firstFailure,new Promise((_,reject)=>setTimeout(()=>reject(new Error('Expected transient save failure')),15000))]);
  await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).draft===null,recordKey,{timeout:20000});
  assert.equal((await Page.findOne({book:book._id,pageNumber:1})).content,'עריכה שהתאוששה מכשל זמני');
  await page.unroute('**/api/page-content');
  console.log('A new edit retried a 503 automatically without another browser event.');

  // Disable the incidental HTTP cache so it cannot mask a missing prepared scan.
  await sharp({create:{width:620,height:920,channels:3,background:'#f0f8ff'}}).png().toFile(path.join(imageDirectory,'refreshed.png'));
  const refreshedImagePath=imagePath.replace('scan.png','refreshed.png');
  await Page.updateOne({book:book._id,pageNumber:1},{$set:{imagePath:refreshedImagePath}});
  await page.reload();
  await page.locator('[data-editor-shell]').waitFor();
  await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).data.thumbnail.endsWith('/refreshed.png'),recordKey);
  assert.equal(await page.evaluate(async k=>{
    const record=JSON.parse(localStorage.getItem(k));
    return Boolean(await (await caches.open(record.cacheName)).match(record.data.thumbnail));
  },recordKey),true);
  const devtools=await context.newCDPSession(page);
  await devtools.send('Network.enable');
  await devtools.send('Network.setCacheDisabled',{cacheDisabled:true});
  await context.setOffline(true);
  await page.reload();
  await page.locator('[data-editor-shell]').waitFor({timeout:20000});
  assert.equal(await page.locator('img[alt]').evaluateAll(els=>els.some(e=>e.naturalWidth>0)),true);
  await page.waitForFunction(()=>Array.from(document.images).some(img=>img.naturalWidth===620));
  // Switch to code view via the persisted preference; plain textarea is easier to assert.
  const rich = page.locator('[data-rich-textarea][contenteditable="true"]');
  const textarea=page.locator('textarea[data-column="content"]');
  const field=await textarea.count()?textarea:rich;
  await field.fill('טקסט שנערך ללא חיבור');
  await page.getByText('נשמר במכשיר · ממתין לסנכרון עם השרת',{exact:false}).waitFor();
  assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).draft.content,recordKey),'טקסט שנערך ללא חיבור');
  await page.reload();
  await page.locator('[data-editor-shell]').waitFor();
  assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).draft.content,recordKey),'טקסט שנערך ללא חיבור');
  await page.screenshot({path:path.join(artifacts,'offline.png'),fullPage:true});
  console.log('Offline reload retained the scan and edited text; second tab was blocked.');
  await context.setOffline(false);
  await page.evaluate(()=>window.dispatchEvent(new Event('online')));
  await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).draft===null,recordKey);
  assert.equal((await Page.findOne({book:book._id,pageNumber:1})).content,'טקסט שנערך ללא חיבור');
  console.log('Reconnection synced the draft to MongoDB.');

  await context.setOffline(true);
  const currentField=page.locator('textarea[data-column="content"], [data-rich-textarea][contenteditable="true"]').first();
  await currentField.fill('טיוטה מקומית מתנגשת');
  await sharp({create:{width:650,height:950,channels:3,background:'#fefcf0'}}).png().toFile(path.join(imageDirectory,'replaced.png'));
  const newImagePath = imagePath.replace('scan.png','replaced.png');
  await Page.updateOne({book:book._id,pageNumber:1},{$set:{content:'תיקון אחר בשרת',imagePath:newImagePath}});
  await context.setOffline(false);
  await page.evaluate(()=>window.dispatchEvent(new Event('online')));
  await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).problem?.code==='OFFLINE_CONFLICT',recordKey);
  assert.equal((await Page.findOne({book:book._id,pageNumber:1})).content,'תיקון אחר בשרת');
  await page.getByRole('button',{name:'ניהול עמודים אופליין'}).click();
  await page.getByRole('button',{name:'השוואה לגרסת השרת'}).click();
  await page.getByRole('textbox',{name:'גרסת השרת',exact:true}).waitFor();
  assert.equal(await page.getByRole('textbox',{name:'גרסת השרת',exact:true}).inputValue(),'תיקון אחר בשרת');
  assert.equal(await page.getByRole('textbox',{name:'הגרסה המקומית',exact:true}).inputValue(),'טיוטה מקומית מתנגשת');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'הורדת גיבוי',exact:true}).click();
  const download=await downloadPromise;
  const backupPath=path.join(artifacts,'backup.json');
  await download.saveAs(backupPath);
  const exported=JSON.parse(fs.readFileSync(backupPath,'utf8'));
  assert.equal(exported.draft.content,'טיוטה מקומית מתנגשת');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:path.join(artifacts,'conflict-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'השתמש בגרסה המקומית',exact:true}).click();
  await page.getByRole('button',{name:'אישור',exact:true}).click();
  await page.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).draft===null,recordKey);
  await page.locator('[data-editor-shell]').waitFor();
  assert.equal((await Page.findOne({book:book._id,pageNumber:1})).content,'טיוטה מקומית מתנגשת');
  assert.equal(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).data.thumbnail,recordKey),newImagePath);
  console.log('Conflict preserved both versions; comparison, backup download, replaced scan and explicit resolution passed at mobile width.');

  // Close the document and expire authentication while offline: only the local identity remains.
  await context.setOffline(true);
  await page.locator('textarea[data-column="content"], [data-rich-textarea][contenteditable="true"]').first().fill('עבודה אחרי סגירה ופקיעת התחברות');
  await context.clearCookies();
  await page.close();
  const reopened=await context.newPage();
  reopened.on('pageerror',e=>errors.push(e.message));
  await reopened.goto(baseUrl+'/library/books/offline-smoke/1');
  await reopened.locator('[data-editor-shell]').waitFor();
  await reopened.waitForFunction(()=>Array.from(document.images).some(img=>img.naturalWidth===650));
  assert.equal(await reopened.getByRole('button',{name:'סיים עמוד',exact:true}).isDisabled(),true);
  await context.setOffline(false);
  await reopened.evaluate(()=>window.dispatchEvent(new Event('online')));
  await reopened.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).problem!==null,recordKey);
  assert.equal(await reopened.evaluate(k=>JSON.parse(localStorage.getItem(k)).draft.content,recordKey),'עבודה אחרי סגירה ופקיעת התחברות');
  await context.addCookies([{name:'next-auth.session-token',value:token,domain:'localhost',path:'/'}]);
  await reopened.evaluate(()=>window.dispatchEvent(new Event('online')));
  await reopened.waitForFunction(k=>JSON.parse(localStorage.getItem(k)).draft===null,recordKey);
  assert.equal((await Page.findOne({book:book._id,pageNumber:1})).content,'עבודה אחרי סגירה ופקיעת התחברות');
  console.log('Closed-tab recovery, expired authentication and successful authenticated retry passed.');
  assert.deepEqual(errors,[]);
  console.log('BROWSER_SMOKE_PASSED');
})().catch(e=>{console.error(e.stack);process.exitCode=1}).finally(async()=>{if(browser)await browser.close();if(app)app.kill('SIGTERM');await mongoose.disconnect();if(mongod)await mongod.stop();fs.closeSync(log);fs.rmSync(imageDirectory,{recursive:true,force:true})});
